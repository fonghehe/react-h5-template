const messages: Record<Locale, Messages> = {
  'zh-CN': zhCN,
  'en-US': enUS,
  'ja-JP': jaJP,
  'zh-HK': zhHK,
  'zh-TW': zhTW,
};

export type MessageKey = keyof typeof zhCN;
export type TranslationValues = Record<string, number | string>;

export function translate(locale: Locale, key: MessageKey, values?: TranslationValues) {
  const message = messages[locale][key];
  if (!values) return message;
  return message.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}

export function formatCurrency(locale: Locale, value: number) {
  return new Intl.NumberFormat(locale, { currency: 'CNY', style: 'currency' }).format(value);
}

